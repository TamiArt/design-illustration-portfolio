const cardSizeSequence = ['wide', 'tall', 'medium', 'wide', 'medium', 'tall'];

function buildSectionCards(section) {
  const cards = [];

  section.images.forEach((entry, index) => {
    if (index === 1) {
      cards.push({
        type: 'text',
        size: 'medium',
        label: section.textCard.label,
        title: section.textCard.title,
        text: section.textCard.text,
      });
    }

    cards.push({
      type: 'image',
      size: cardSizeSequence[index % cardSizeSequence.length],
      image: entry.image,
      label: entry.label,
      title: entry.title,
      text: entry.text,
    });
  });

  return cards;
}

export const journalStories = Object.fromEntries(
  portfolioSections.map((section) => [
    section.id,
    {
      intro: section.intro,
      cta: section.cta,
      cards: buildSectionCards(section),
    },
  ]),
);

